def test_tools_run_rejects_direct_tool_injection():
    with patch(
        "app.api.run_read_only_tool_request",
    ) as mock_run:
        response = client.post(
            "/tools/run",
            json={
                "question": (
                    "List pods in namespace ai-ops-demo."
                ),
                "tool": "k8s.delete_pod",
                "arguments": {
                    "namespace": "ai-ops-demo",
                    "pod": (
                        "payments-api-"
                        "8557447b4-4bm8n"
                    ),
                },
            },
        )

    assert response.status_code == 422

    # Validation must reject the request before orchestration.
    mock_run.assert_not_called()


